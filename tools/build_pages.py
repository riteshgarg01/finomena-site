"""Build one HTML file per page so every page has its own URL, title and description.

index.html stays the only file you edit. This script copies it to <route>/index.html for every entry in its
pageMeta block, with that page's title, description, canonical URL and social tags, and with that page visible in
the HTML itself (the script still routes as usual). It also writes sitemap.xml, robots.txt and 404.html.

Run after every change to index.html, from the repo root:  python3 tools/build_pages.py
"""
import datetime, html, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = 'https://finomenahq.com'
STAMP = '<!-- Generated by tools/build_pages.py from index.html. Do not edit; edit index.html and re-run. -->\n'

src = (ROOT / 'index.html').read_text()
meta = json.loads(re.search(r'<script type="application/json" id="pageMeta">(.*?)</script>', src, re.S).group(1))


def url(key):
    return SITE + ('/' if key == 'home' else f'/{key}/')


def sub(pattern, repl, text):
    out, n = re.subn(pattern, lambda m: repl, text, count=1)
    assert n == 1, pattern
    return out


def page_html(key, title, desc, noindex=False):
    t, d, u = html.escape(title, quote=True), html.escape(desc, quote=True), url(key)
    h = src
    h = sub(r'<title>.*?</title>', f'<title>{t}</title>', h)
    h = sub(r'<meta name="description" content="[^"]*">', f'<meta name="description" content="{d}">', h)
    h = sub(r'<link rel="canonical" href="[^"]*">', f'<link rel="canonical" href="{u}">', h)
    h = sub(r'<meta property="og:title" content="[^"]*">', f'<meta property="og:title" content="{t}">', h)
    h = sub(r'<meta property="og:description" content="[^"]*">', f'<meta property="og:description" content="{d}">', h)
    h = sub(r'<meta property="og:url" content="[^"]*">', f'<meta property="og:url" content="{u}">', h)
    h = sub(r'<meta name="twitter:title" content="[^"]*">', f'<meta name="twitter:title" content="{t}">', h)
    h = sub(r'<meta name="twitter:description" content="[^"]*">', f'<meta name="twitter:description" content="{d}">', h)
    if noindex:
        h = h.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n<meta name="robots" content="noindex">', 1)
    # show this page in the HTML itself, for crawlers and link previews that don't run scripts
    page, _, rest = key.partition('/')
    if page != 'home':
        h = sub(r'<div data-page="home">', '<div data-page="home" hidden>', h)
        h = sub(rf'<div data-page="{page}" hidden>', f'<div data-page="{page}">', h)
    if page == 'insights' and rest:
        h = sub(r'<div id="postIndex">', '<div id="postIndex" hidden>', h)
        h = re.sub(rf'(<article class="post" data-article="{re.escape(rest)}"[^>]*?) hidden>', r'\1>', h, count=1, flags=re.S)
    return h.replace('<!doctype html>\n', '<!doctype html>\n' + STAMP, 1)


# clear what an earlier run generated: only files carrying our stamp, then folders left empty
for f in ROOT.rglob('index.html'):
    if f.parent != ROOT and '.claude' not in f.parts and STAMP.strip() in f.read_text():
        f.unlink()
for d in sorted((p for p in ROOT.rglob('*') if p.is_dir() and '.git' not in p.parts and '.claude' not in p.parts),
                key=lambda p: len(p.parts), reverse=True):
    if not any(d.iterdir()):
        d.rmdir()

written = []
for key, (title, desc) in meta.items():
    if key == 'home':
        continue  # index.html itself is the home page
    out = ROOT / key / 'index.html'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page_html(key, title, desc))
    written.append(key)

(ROOT / '404.html').write_text(page_html('home', 'Page not found · Finomena', meta['home'][1], noindex=True))
today = datetime.date.today().isoformat()
(ROOT / 'sitemap.xml').write_text('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
                                 + ''.join(f'  <url><loc>{url(k)}</loc><lastmod>{today}</lastmod></url>\n' for k in meta)
                                 + '</urlset>\n')
(ROOT / 'robots.txt').write_text(f'User-agent: *\nAllow: /\nSitemap: {SITE}/sitemap.xml\n')
print(f'{len(written)} pages + 404.html, sitemap.xml ({len(meta)} URLs), robots.txt')
